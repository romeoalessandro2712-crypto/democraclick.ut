let current = 'it';

export function getLang() { return current; }

export function t(key, vars) {
  let s = (dict[current] && dict[current][key]) ?? dict.it[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
  return s;
}

/** Apply translations to every [data-i18n] (text) and [data-i18n-aria] (aria-label). */
export function applyI18n(lang, root = document) {
  if (dict[lang]) current = lang;
  document.documentElement.lang = current;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-lang]').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === current)));
  try { localStorage.setItem('dc-lang', current); } catch (e) { /* storage unavailable */ }
  document.dispatchEvent(new CustomEvent('dc:lang', { detail: current }));
}

export function initialLang() {
  try { const s = localStorage.getItem('dc-lang'); if (s && dict[s]) return s; } catch (e) { /* ignore */ }
  return 'it';
}
